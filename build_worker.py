# Bundles the app into one Cloudflare Worker file (worker.js).
# Run: python3 build_worker.py   (then upload worker.js)
import base64, json
files = {
  "/index.html": "text/html; charset=utf-8",
  "/style.css": "text/css; charset=utf-8",
  "/app.js": "text/javascript; charset=utf-8",
  "/sw.js": "text/javascript; charset=utf-8",
  "/manifest.json": "application/manifest+json",
  "/apple-touch-icon.png": "image/png",
  "/icon-192.png": "image/png",
  "/icon-512.png": "image/png",
}
table = {p: [t, base64.b64encode(open(p[1:], "rb").read()).decode()] for p, t in files.items()}
open("worker.js", "w").write("""// Generated by build_worker.py. Don't edit by hand.
const FILES = %s;
export default {
  fetch(req) {
    let path = new URL(req.url).pathname;
    if (path === '/') path = '/index.html';
    const f = FILES[path];
    if (!f) return new Response('Not found', { status: 404 });
    const bytes = Uint8Array.from(atob(f[1]), (c) => c.charCodeAt(0));
    return new Response(bytes, { headers: { 'content-type': f[0], 'cache-control': 'no-cache' } });
  },
};
""" % json.dumps(table))
